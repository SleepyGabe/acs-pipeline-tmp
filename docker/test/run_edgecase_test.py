    """CREATE TABLE {S}.EDGE_ROWID (ID NUMBER(5) PRIMARY KEY, RID ROWID)""",
    "INSERT INTO {S}.EDGE_ROWID (ID) VALUES (1)",

    # F5 CHECK w/ Oracle-only fns: INSTR (now -> strpos) + NVL2 (unconvertible). Pre-fix
