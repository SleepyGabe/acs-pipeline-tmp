    f'ID NUMBER(5) PRIMARY KEY, "{_LONG_A}" NUMBER(5), "{_LONG_B}" NUMBER(5) )',
    f'INSERT INTO {{S}}.EDGE_LONGID (ID, "{_LONG_A}", "{_LONG_B}") VALUES (1, 10, 20)',

